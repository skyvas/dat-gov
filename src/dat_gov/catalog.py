"""Catalog builder: YAML governance files + real Parquet schemas -> docs.

Governance idea demonstrated here: a catalog that is generated from
the same files the pipeline enforces cannot drift from reality. If a
contract adds a column, the data dictionary gains it on the next run;
if a dataset has no catalog entry, the build (and the governance test)
fails loudly instead of letting an undocumented dataset slip through.
"""

from __future__ import annotations

from pathlib import Path

import duckdb
import yaml

from .config import CATALOG_DIR, CONTRACTS_DIR, DATA_DIR, DOCS_DIR, SILVER_DIR
from .lineage import build_lineage


def _load_yaml(path: Path) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def build_catalog(docs_dir: Path = DOCS_DIR, silver_dir: Path = SILVER_DIR) -> Path:
    """Write docs/catalog.md and data/lineage.json. Returns the catalog path."""
    docs_dir.mkdir(parents=True, exist_ok=True)
    con = duckdb.connect()
    lines = ["# Data Catalog — Northbridge University\n",
             "Generated by `src/dat_gov/catalog.py` from `governance/catalog/*.yaml`, "
             "`governance/contracts/*.yaml` and the actual Silver Parquet schemas. Do not edit by hand.\n",
             "## Datasets\n"]
    try:
        for path in sorted(CATALOG_DIR.glob("*.yaml")):
            entry = _load_yaml(path)
            contract = _load_yaml(CONTRACTS_DIR / f"{entry['dataset']}.yaml")
            lines.append(f"### {entry['dataset']} (`{entry['subdomain']}`)\n")
            lines.append(f"{entry['description']}\n")
            lines.append(f"- **Owner:** {entry['owner']} | **Classification:** {entry['classification']} | "
                         f"**Source:** {entry['source_system']} | **Retention:** {entry['retention_years']} years")
            pii = entry.get("pii_fields") or []
            lines.append(f"- **PII fields:** {', '.join(pii) if pii else 'none'}")
            lines.append(f"- **Downstream:** {', '.join(entry.get('downstream') or ['—'])}\n")
            lines.append("| Column | Type | Nullable | PII | Description |")
            lines.append("|---|---|---|---|---|")
            # Prefer the real Silver schema when the pipeline has run.
            silver_path = silver_dir / f"{entry['dataset']}.parquet"
            real_types: dict[str, str] = {}
            if silver_path.exists():
                for col, typ, *_ in con.execute(f"DESCRIBE SELECT * FROM read_parquet('{silver_path}')").fetchall():
                    real_types[col] = typ
            for col in contract["columns"]:
                lines.append(f"| {col['name']} | {real_types.get(col['name'], col['type'])} | "
                             f"{col['nullable']} | {col.get('pii', '—')} | {col['description']} |")
            lines.append("")
    finally:
        con.close()
    lines.append("## Lineage\n\nSee [lineage.md](lineage.md) and `data/lineage.json`.\n")
    out = docs_dir / "catalog.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    # Lineage JSON lives next to the data it describes.
    import json as _json
    (DATA_DIR / "lineage.json").write_text(_json.dumps(build_lineage(), indent=2), encoding="utf-8")
    return out
